#!/usr/bin/env python3
"""python deception/configure.py: write build/deception/build.ninja (then ninja -f build/deception/build.ninja).

Builds the GC 2.7 frontend reconstruction (deception/src/frontend) with the compiler that builds 1.3's, the AST oracle
(the original executable with deception/tools/astdump.c in front of CodeGen_Generator: build/deception/oracle.exe)
and the hybrid (the oracle with the functions deception/config/inject.json lists replaced:
build/deception/hybrid.exe). Needs the main project built for GC_2_7 once (python configure.py --version GC_2_7 &&
ninja), for the compilers and the original.
"""
import json
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPILER = "build/compilers/pro6/mwcc.exe"


def main():
    sources = json.loads((ROOT / "config/sources.json").read_text())
    inject = json.loads((ROOT / "deception/config/inject.json").read_text())
    python = shlex.quote(sys.executable)
    out = [
        "# Generated by deception/configure.py",
        f"python = {python}",
        "wibo = build/tools/wibo",
        "rule mwcc",
        "  command = MWCIncludes=include/libc $wibo " + COMPILER + " $cflags $in -o $out",
        "  description = MWCC $in",
        "rule link",
        "  command = $python deception/tools/hybrid.py $out $args",
        "  description = LINK $out",
        "rule configure",
        "  command = $python deception/configure.py",
        "  generator = 1",
        "",
    ]
    objects = {}
    units = sorted(Path(ROOT / "deception/src/frontend").glob("*.c"))
    for unit in units:
        source = unit.relative_to(ROOT).as_posix()
        settings = sources["src/frontend/" + unit.name]
        include_dirs = [d.replace("src/frontend", "deception/src/frontend").replace("include", "deception/include")
                        if d in ("src/frontend", "include") else d for d in settings.get("include_dirs", [])]
        args = ["-c", *settings["flags"], *(f"-I{d}" for d in include_dirs), "-Ideception/include", "-Iinclude",
                "-i-", "-Iinclude/libc"]
        obj = f"build/deception/compiled/{source}.obj"
        out += [f"build {obj}: mwcc {source} | $wibo {COMPILER}", f"  cflags = {shlex.join(args)}"]
        objects[source] = obj
    oracle_obj = "build/deception/compiled/deception/tools/astdump.c.obj"
    out += [f"build {oracle_obj}: mwcc deception/tools/astdump.c | $wibo {COMPILER}",
            "  cflags = -c -O4,p -inline auto -Cpp_exceptions off -Ideception/include -Iinclude -i- -Iinclude/libc"]
    tools = "deception/tools/hybrid.py config/GC_2_7/functions.json config/GC_2_7/bindings.json"
    out += [f"build build/deception/oracle.exe: link {oracle_obj} | {tools}", f"  args = --hook {oracle_obj}"]
    injected = []
    for source, names in sorted(inject.items()):
        injected += [f"--inject {objects[source]}:{name}" for name in names]
    inputs = " ".join(sorted({objects[s] for s in inject}))
    out += [f"build build/deception/hybrid.exe: link {oracle_obj} {inputs} | {tools} deception/config/inject.json",
            f"  args = --hook {oracle_obj} {' '.join(injected)}"]
    out += [f"build all_frontend: phony {' '.join(objects.values())}",
            "build build/deception/build.ninja: configure | deception/configure.py config/sources.json"
            " deception/config/inject.json",
            "default build/deception/oracle.exe build/deception/hybrid.exe all_frontend", ""]
    (ROOT / "build/deception").mkdir(parents=True, exist_ok=True)
    (ROOT / "build/deception/build.ninja").write_text("\n".join(out))


if __name__ == "__main__":
    main()
